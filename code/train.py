def parse_args(argv=None):
    preliminary = argparse.ArgumentParser(add_help=False)
    preliminary.add_argument("--config", type=Path)
    known, _ = preliminary.parse_known_args(argv)
    defaults = {}
    if known.config:
        defaults = json.loads(known.config.read_text())
        if not isinstance(defaults, dict):
            raise ValueError("Configuration must be a JSON object")
    parser = argparse.ArgumentParser(description=__doc__, parents=[preliminary])
    parser.add_argument("--manifest", default=DEFAULT_MANIFEST)
    parser.add_argument("--augmented-manifest", default=None)
    parser.add_argument("--selection-manifest", default=None,
                        help="Fixed reproducible training selection; never regenerated by the trainer")
    parser.add_argument("--augmentation-groups", nargs="*", default=[])
    parser.add_argument("--train-source", choices=("original", "augmented", "combined"), default="original")
    parser.add_argument("--decoder", choices=("pixel", "region"), default="region")
    parser.add_argument("--backbone", choices=("dual", "convnext"), default="dual")
    parser.add_argument("--input-size", type=int, default=1024)
    parser.add_argument("--num-queries", type=int, default=32)
    parser.add_argument("--decoder-layers", type=int, default=4)
    parser.add_argument("--weight-dir", default="model")
    parser.add_argument("--convnext-checkpoint", default=None,
                        help="Optional matching ConvNeXt checkpoint, including a saved previous LuSNAR model")
    parser.add_argument("--initial-checkpoint", default=None,
                        help="Initialize all model weights strictly from this checkpoint; start a new optimizer/schedule")
    parser.add_argument("--design-selection-reference", default=None,
                        help="Saved recipe decision and test-use provenance; does not use test data to choose epochs")
    parser.add_argument("--output", default="result/dual_region_1024")
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--freeze-epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--val-batch-size", type=int, default=2)
    parser.add_argument("--accumulation", type=int, default=4)
    parser.add_argument("--head-lr", type=float, default=1e-4)
    parser.add_argument("--backbone-lr", type=float, default=1e-5)
    parser.add_argument("--weight-decay", type=float, default=0.01)
    parser.add_argument("--gradient-clip", type=float, default=1.0)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--amp", choices=("bf16", "fp16", "none"), default="bf16")
    parser.add_argument("--val-tta", choices=("none", "hflip", "multiscale_hflip"), default="none",
                        help="Validation only: none, horizontal flip, or multiscale plus horizontal flip")
    parser.add_argument("--val-tta-sizes", nargs="+", type=int, default=None,
                        help="Explicit inference sizes for multiscale_hflip validation, e.g. 1024 768")
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--horizontal-flip", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--resume", default=None)
    parser.add_argument("--max-train-samples", type=int, default=None)
    parser.add_argument("--max-val-samples", type=int, default=None)
    parser.add_argument("--num-points", type=int, default=4096)
    parser.add_argument("--hard-pixel-weight", type=float, default=0.0,
                        help="Weight of the additional direction-balanced hard-pixel CE; zero preserves the base objective")
    parser.add_argument("--hard-pixel-quota", type=int, default=256,
                        help="Maximum hard pixels per image and confusion direction")
    parser.add_argument("--pretrained", action=argparse.BooleanOptionalAction, default=True)
    allowed = {action.dest for action in parser._actions}
    unknown = set(defaults) - allowed
    if unknown:
        parser.error(f"Unknown JSON configuration keys: {sorted(unknown)}")
    parser.set_defaults(**defaults)
    args = parser.parse_args(argv)
    for key in ("epochs", "batch_size", "val_batch_size", "accumulation", "num_points"):
        if getattr(args, key) < 1:
            parser.error(f"{key} must be positive")
    if not 0 <= args.freeze_epochs <= args.epochs:
        parser.error("freeze_epochs must be between zero and epochs")
    if args.workers < 0 or min(args.head_lr, args.backbone_lr) <= 0:
        parser.error("workers must be nonnegative and learning rates positive")
    if (isinstance(args.hard_pixel_weight, bool) or not isinstance(args.hard_pixel_weight, (int, float))
            or not math.isfinite(args.hard_pixel_weight) or args.hard_pixel_weight < 0):
        parser.error("hard_pixel_weight must be finite and nonnegative")
    if (isinstance(args.hard_pixel_quota, bool) or not isinstance(args.hard_pixel_quota, int)
            or args.hard_pixel_quota < 0):
        parser.error("hard_pixel_quota must be a nonnegative integer")
    if args.initial_checkpoint and (args.resume or args.convnext_checkpoint):
        parser.error("initial_checkpoint is mutually exclusive with resume and convnext_checkpoint")
    try:
        args.val_tta_sizes = validate_tta_sizes(args.val_tta, args.val_tta_sizes)
    except ValueError as error:
        parser.error(str(error))
    for key in ("manifest", "augmented_manifest", "selection_manifest", "weight_dir", "convnext_checkpoint",
                "initial_checkpoint", "design_selection_reference", "output", "resume"):
        value = getattr(args, key)
        if value:
            path = Path(value)
            setattr(args, key, str(path.resolve() if path.is_absolute() else (PROJECT / path).resolve()))
    args.config = str(known.config.resolve()) if known.config else None
    return args


def seed_worker(_worker_id):
    seed = torch.initial_seed() % (2 ** 32)
    random.seed(seed)
    np.random.seed(seed)


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True


def rng_state(device):
    state = np.random.get_state()
    return {"python": random.getstate(), "torch": torch.get_rng_state(),
            "cuda": {"device_index": device.index if device.index is not None else torch.cuda.current_device(),
                     "state": torch.cuda.get_rng_state(device)} if device.type == "cuda" else None,
            "numpy": {"name": state[0], "keys": state[1].tolist(), "pos": state[2],
                      "has_gauss": state[3], "cached_gaussian": state[4]}}


def restore_rng(state, device):
    random.setstate(state["python"])
    torch.set_rng_state(state["torch"].cpu())
    if state["cuda"] and device.type == "cuda":
        cuda = state["cuda"]
        # A resumed run may select another GPU; restore this run's RNG on its
        # current device without creating contexts on unrelated GPUs.
        value = cuda[0] if isinstance(cuda, list) else cuda["state"]
        torch.cuda.set_rng_state(value.cpu(), device=device)
    value = state["numpy"]
    np.random.set_state((value["name"], np.asarray(value["keys"], dtype=np.uint32), value["pos"],
                         value["has_gauss"], value["cached_gaussian"]))


def write_json(path, value):
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")
    temporary.replace(path)


def save_checkpoint(path, checkpoint):
    temporary = path.with_suffix(path.suffix + ".tmp")
    torch.save(checkpoint, temporary)
    temporary.replace(path)


def model_tensor_hashes(model):
    """Hash canonical tensor names, shapes, dtypes and bytes without using RNG."""
    digests = {name: hashlib.sha256() for name in ("model", "backbones", "heads")}
    count = 0
    for name, tensor in sorted(model.state_dict().items()):
        value = tensor.detach().cpu().contiguous()
        header = json.dumps([name, str(value.dtype), list(value.shape)], separators=(",", ":")).encode() + b"\n"
        raw = memoryview(value.reshape(-1).view(torch.uint8).numpy())
        for group in ("model", "backbones" if name.startswith("encoder.") else "heads"):
            digests[group].update(header)
            digests[group].update(raw)
        count += 1
    return {"algorithm": "sha256_sorted_state_dict_name_dtype_shape_raw_bytes_v1",
            "tensor_count": count, **{name + "_sha256": digest.hexdigest() for name, digest in digests.items()}}


def pretrained_provenance(model, weight_dir):
    provenance = {"backbones": model.pretrained_report}
    for report in provenance["backbones"].values():
        if report and report.get("loaded") and report.get("path"):
            report["sha256"] = sha256_file(report["path"])
    for weight_manifest in sorted(Path(weight_dir).glob("*manifest*.json")):
        provenance[weight_manifest.name] = {"content": json.loads(weight_manifest.read_text()),
                                             "sha256": sha256_file(weight_manifest)}
    return provenance


def initialization_mode(args, previous=None):
    if previous is not None and previous.get("initialization_mode"):
        return previous["initialization_mode"]
    values = previous if previous is not None else vars(args)
    if values.get("initial_checkpoint"):
        return "checkpoint_finetune"
    if not values.get("pretrained", True):
        return "random"
    return "convnext_checkpoint" if values.get("convnext_checkpoint") else "original_pretrained"


def design_selection_reference(args, mode, previous=None):
    """Validate and embed the recipe decision without evaluating test images."""
    raw_path = args.design_selection_reference
    if previous is not None and not raw_path:
        raw_path = previous.get("design_selection_reference")
    if raw_path:
        path = Path(raw_path)
        path = path.resolve() if path.is_absolute() else (PROJECT / path).resolve()
        with path.open("rb") as stream:
            raw = stream.read()
        fingerprint = hashlib.sha256(raw).hexdigest()
        document = json.loads(raw)
    else:
        path, fingerprint, document = None, None, None
    if previous is not None and previous.get("design_selection_reference_sha256") != fingerprint:
        raise ValueError("Resume design-selection reference SHA256 differs; retain the original recipe decision")
    if document is not None:
        if not isinstance(document, dict) or document.get("schema") != "lusnar_test_selected_recipe_v1":
            raise ValueError("Unsupported design-selection reference schema")
        if document.get("selected_using_test") is not True:
            raise ValueError("A test-selected recipe reference must explicitly declare selected_using_test=true")
        if not isinstance(document.get("selected_run"), str) or not document["selected_run"]:
            raise ValueError("Design-selection reference needs selected_run")
        if (type(document.get("selected_checkpoint_epoch")) is not int
                or document["selected_checkpoint_epoch"] < 1):
            raise ValueError("Invalid selected checkpoint epoch or test TTA in recipe reference")
        validate_tta_sizes(document.get("selected_test_tta"), document.get("selected_test_tta_sizes"))
        score = document.get("selected_weighted_score")
        if isinstance(score, bool) or not isinstance(score, (int, float)) or not math.isfinite(score) or not 0 <= score <= 1:
            raise ValueError("Selected weighted score must be a finite fraction between zero and one")
        for field in ("selected_checkpoint", "selected_metrics_file"):
            value = document.get(field)
            if not isinstance(value, str) or not value:
                raise ValueError(f"Design-selection reference needs {field}")
            source_path = Path(value)
            source_path = source_path.resolve() if source_path.is_absolute() else (PROJECT / source_path).resolve()
            expected_sha = document.get(field + "_sha256")
            if field == "selected_metrics_file" and "selected_metrics_sha256" in document:
                if expected_sha is not None and expected_sha != document["selected_metrics_sha256"]:
                    raise ValueError("Conflicting selected metrics SHA256 fields in recipe reference")
                expected_sha = document["selected_metrics_sha256"]
            if (not isinstance(expected_sha, str) or len(expected_sha) != 64
                    or any(character not in "0123456789abcdef" for character in expected_sha)):
                raise ValueError(f"Recipe reference needs a valid {field} SHA256")
            # Exact resume already carries the selected model/optimizer and the
            # unchanged embedded reference. Its original source checkpoints may
            # have been archived; do not reload or require those files again.
            if previous is None and expected_sha != sha256_file(source_path):
                raise ValueError(f"Design-selection reference {field} SHA256 differs from its source file")
        if document.get("initialization_mode") != mode:
            raise ValueError("Recipe initialization_mode differs from the actual training initialization")
        if "new_split_manifest" in document or "new_split_manifest_sha256" in document:
            value = document.get("new_split_manifest")
            if not isinstance(value, str) or not value:
                raise ValueError("Recipe reference needs both new_split_manifest and its SHA256")
            split_path = Path(value)
            split_path = split_path.resolve() if split_path.is_absolute() else (PROJECT / split_path).resolve()
            if split_path != Path(args.manifest) or document.get("new_split_manifest_sha256") != sha256_file(args.manifest):
                raise ValueError("Recipe reference new split manifest path/SHA256 differs from training")
        recipe = document.get("training_recipe")
        if not isinstance(recipe, dict) or not isinstance(document.get("candidate_results"), (list, dict)) or not document["candidate_results"]:
            raise ValueError("Recipe reference needs training_recipe and nonempty candidate_results")
        fields = ("decoder", "backbone", "input_size", "num_queries", "decoder_layers", "hard_pixel_weight",
                  "hard_pixel_quota", "batch_size", "accumulation", "head_lr", "backbone_lr",
                  "freeze_epochs", "epochs", "val_tta", "val_tta_sizes", "seed")
        for field in fields:
            if field in recipe and recipe[field] != getattr(args, field):
                raise ValueError(f"Recipe reference training setting {field} differs from the requested run")
        if mode == "checkpoint_finetune" and previous is None:
            if sha256_file(args.initial_checkpoint) != document["selected_checkpoint_sha256"]:
                raise ValueError("initial_checkpoint differs from the test-selected checkpoint")
    return {"design_selection_reference": str(path) if path else None,
            "design_selection_reference_sha256": fingerprint,
            "design_selection_reference_data": document}


def training_loss_means(sums, seen):
    means = {name: value / seen for name, value in sums.items()}
    means["hard_to_base_ratio"] = means["loss_hard_pixels_weighted"] / max(means["loss_base"], 1e-12)
    return means


HARD_DIRECTIONS = ("0->3", "3->0", "2->0", "0->2", "3->1", "1->3")
HARD_COUNT_FIELDS = ("candidate_count", "selected_count", "selected_ce_sum",
                     "candidate_boundary_count", "selected_boundary_count")


class HardPixelDiagnostics:
    """Bounded, detached training examples for examining labels; no re-mining."""

    def __init__(self, dataset, weight, quota):
        self.dataset, self.weight, self.quota = dataset, weight, quota
        self.enabled = weight > 0 and quota > 0
        self.records = {(row["scene"], str(row["sample_id"])): row for row in dataset.records}
        self.stats = {direction: {name: 0 for name in HARD_COUNT_FIELDS} for direction in HARD_DIRECTIONS}
        self.examples = {direction: {} for direction in HARD_DIRECTIONS}
        self.batch_count = 0
        self.source_counts = dict(Counter(self.source_group(row) for row in dataset.records))

    @staticmethod
    def source_group(row):
        return "augmented/" + row["augmentation_group"] if row.get("augmentation_group") else "original"

    def update(self, criterion, batch, step):
        self.batch_count += 1
        if not self.enabled:
            return
        for direction, values in criterion.latest_hard_pixel_stats.items():
            for name in HARD_COUNT_FIELDS:
                self.stats[direction][name] += values[name]
        for point in criterion.latest_hard_examples:
            direction, index = point["direction"], int(point["batch_index"])
            scene, sample_id = batch["scene"][index], str(batch["sample_id"][index])
            row = self.records[(scene, sample_id)]
            flipped = bool(batch["horizontal_flipped"][index])
            key = (scene, sample_id)
            height, width = batch["mask"].shape[-2:]
            x, y = int(point["x"]), int(point["y"])
            entry = self.examples[direction].setdefault(key, {
                "scene": scene, "sample_id": sample_id, "source_id": row["source_id"],
                "source_kind": row.get("source_kind", "augmented" if row.get("augmentation_group") else "original"),
                "augmentation_group": row.get("augmentation_group"),
                "image": str(Path(row["image"]).resolve()), "mask": str(Path(row["mask"]).resolve()),
                "horizontal_flipped": flipped, "input_height": height, "input_width": width,
                "batch_number": step + 1, "points": []})
            entry["points"].append({"training_x": x, "training_y": y,
                                    "unflipped_input_x": width - 1 - x if flipped else x,
                                    "unflipped_input_y": y, "gt": int(point["gt"]),
                                    "pred": int(point["pred"]), "ce": float(point["ce"]),
                                    "gt_boundary": bool(point["boundary"])})
            entry["points"] = sorted(entry["points"], key=lambda p: (-p["ce"], p["training_y"], p["training_x"]))[:4]
            ordered = sorted(self.examples[direction].items(),
                             key=lambda pair: (-pair[1]["points"][0]["ce"], pair[0]))
            self.examples[direction] = dict(ordered[:8])

    def result(self, epoch, losses):
        directions = {}
        for direction in HARD_DIRECTIONS:
            values = dict(self.stats[direction])
            values["candidate_boundary_fraction"] = (values["candidate_boundary_count"] / values["candidate_count"]
                                                     if values["candidate_count"] else None)
            values["selected_boundary_fraction"] = (values["selected_boundary_count"] / values["selected_count"]
                                                    if values["selected_count"] else None)
            values["selected_mean_ce"] = (values["selected_ce_sum"] / values["selected_count"]
                                          if values["selected_count"] else None)
            examples = list(self.examples[direction].values())
            for example in examples:
                if "native_width" not in example:
                    with Image.open(example["mask"]) as source:
                        example.update(native_width=source.width, native_height=source.height)
                native_width, native_height = example["native_width"], example["native_height"]
                for point in example["points"]:
                    point["source_x"] = min(native_width - 1, int((point["unflipped_input_x"] + 0.5)
                                                                 * native_width / example["input_width"]))
                    point["source_y"] = min(native_height - 1, int((point["unflipped_input_y"] + 0.5)
                                                                  * native_height / example["input_height"]))
            directions[direction] = {**values, "highest_ce_examples": examples}
        return {"schema": "lusnar_hard_pixel_diagnostics_v1", "epoch": epoch, "enabled": self.enabled,
                "hard_pixel_weight": self.weight, "hard_pixel_quota": self.quota,
                "training_data_identity": self.dataset.identity, "training_source_counts": self.source_counts,
                "training_batches": self.batch_count,
                "direction_definition": "GT class ID -> current predicted class ID; training data only",
                "hard_objective_normalization": "Mean selected CE per image and direction, empty directions zero, then mean across batch x 6; selected_mean_ce below is pooled for diagnosis",
                "boundary_definition": "Chebyshev radius-3 neighborhood contains another GT class; ignore out-of-image pixels; not excluded from mining",
                "coordinate_definition": "training_x/y after optional horizontal flip; source_x/y undo flip and inverse-resize pixel centers",
                "example_selection": "Highest selected-pixel CE, at most 8 samples per direction and 4 points per sample; not evidence of label error",
                "training_loss": losses, "directions": directions}


def main(argv=None):
    args = parse_args(argv)
    device = torch.device(args.device)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA is unavailable; use the lzc_fenge GPU environment or --device cpu")
    if device.type == "cuda":
        if device.index is None:
            device = torch.device("cuda", torch.cuda.current_device())
        torch.cuda.set_device(device)
    seed_everything(args.seed)
    if device.type == "cuda" and args.amp == "bf16" and not torch.cuda.is_bf16_supported():
        raise RuntimeError("This GPU does not support BF16; use --amp fp16 or none")
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    if (output / "last.pt").exists() and not args.resume:
        raise FileExistsError("Output already has last.pt; resume explicitly or select a new output directory")
    train_data = LunarDataset(args.manifest, "train", args.input_size,
                              args.augmented_manifest, args.augmentation_groups,
                              args.train_source, args.horizontal_flip, args.max_train_samples,
                              selection_manifest=args.selection_manifest)
    val_data = LunarDataset(args.manifest, "val", args.input_size, max_samples=args.max_val_samples)
    custom_validation = val_data.identity.get("custom_split", False)
    selection_scene = "custom_validation" if custom_validation else "Moon_5"
    partial = train_data.partial or val_data.partial
    generator = torch.Generator().manual_seed(args.seed)
    val_generator = torch.Generator().manual_seed(args.seed + 1)
    train_loader = DataLoader(train_data, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.workers, pin_memory=device.type == "cuda", drop_last=False,
                              generator=generator, worker_init_fn=seed_worker, persistent_workers=False)
    val_loader = DataLoader(val_data, batch_size=args.val_batch_size, shuffle=False,
                            num_workers=args.workers, pin_memory=device.type == "cuda", drop_last=False,
                            generator=val_generator, worker_init_fn=seed_worker, persistent_workers=False)
    config = ModelConfig(decoder=args.decoder, backbone=args.backbone, input_size=args.input_size,
                         num_classes=5, num_queries=args.num_queries, decoder_layers=args.decoder_layers,
                         weight_dir=args.weight_dir, convnext_checkpoint=args.convnext_checkpoint)
    saved = None
    if args.resume:
        saved = torch.load(args.resume, map_location="cpu", weights_only=True)
        if saved["model_config"] != config.to_dict():
            raise ValueError("Resume model configuration differs from checkpoint")
        if saved["data_identity"] != {"train": train_data.identity, "val": val_data.identity}:
            raise ValueError("Resume dataset identity differs from checkpoint")
        previous = saved["run_config"]
        for field in ("freeze_epochs", "batch_size", "accumulation", "head_lr", "backbone_lr",
                      "weight_decay", "gradient_clip", "val_batch_size", "seed", "horizontal_flip",
                      "amp", "num_points", "workers", "epochs"):
            if previous[field] != getattr(args, field):
                raise ValueError(f"Resume setting {field} differs; exact continuation requires the saved training schedule")
        if previous.get("val_tta", "none") != args.val_tta:
            raise ValueError("Resume setting val_tta differs; preserve the checkpoint selection protocol")
        if previous.get("val_tta_sizes") != args.val_tta_sizes:
            raise ValueError("Resume setting val_tta_sizes differs; preserve the checkpoint selection protocol")
        for field, default in (("hard_pixel_weight", 0.0), ("hard_pixel_quota", 256)):
            if previous.get(field, default) != getattr(args, field):
                raise ValueError(f"Resume setting {field} differs; changing the objective requires a new run")
    mode = initialization_mode(args, saved["run_config"] if saved else None)
    reference = design_selection_reference(args, mode, saved["run_config"] if saved else None)
    test_selected_recipe = bool(reference["design_selection_reference_data"]
                                and reference["design_selection_reference_data"]["selected_using_test"])
    model = build_model(config, pretrained=args.pretrained and saved is None and not args.initial_checkpoint).to(device)
    initial_checkpoint_sha256, initial_checkpoint_epoch, parent_pretrained_report = None, None, None
    if args.initial_checkpoint:
        initial_checkpoint_sha256 = sha256_file(args.initial_checkpoint)
        initial = torch.load(args.initial_checkpoint, map_location="cpu", weights_only=True)
        model.load_state_dict(initial.get("model", initial), strict=True)
        initial_checkpoint_epoch = initial.get("epoch")
        parent_pretrained_report = initial.get("pretrained_report")
        if sha256_file(args.initial_checkpoint) != initial_checkpoint_sha256:
            raise ValueError("Initial checkpoint changed while reading its weights")
        del initial
    elif saved:
        initial_checkpoint_sha256 = saved["run_config"].get("initial_checkpoint_sha256")
        initial_checkpoint_epoch = saved["run_config"].get("initial_checkpoint_epoch")
    initialization = saved["run_config"].get("initial_model_tensor_hashes") if saved else model_tensor_hashes(model)
    initial_model_sha256 = (saved["run_config"].get("initial_model_sha256") if saved
                            else initialization["model_sha256"])
    criterion = SegmentationCriterion(num_classes=5, num_points=args.num_points,
                                      hard_pixel_weight=args.hard_pixel_weight,
                                      hard_pixel_quota=args.hard_pixel_quota).to(device)
    optimizer = torch.optim.AdamW([
        {"params": list(model.backbone_parameters()), "lr": args.backbone_lr, "group_name": "backbone"},
        {"params": list(model.head_parameters()), "lr": args.head_lr, "group_name": "head"},
    ], weight_decay=args.weight_decay)
    scaler = torch.cuda.amp.GradScaler(enabled=device.type == "cuda" and args.amp == "fp16")
    start_epoch, best, best_epoch, update = 0, -math.inf, None, 0
    if saved:
        model.load_state_dict(saved["model"], strict=True)
        optimizer.load_state_dict(saved["optimizer"])
        scaler.load_state_dict(saved["scaler"])
        start_epoch, best = saved["epoch"], saved["best_miou"]
        best_epoch, update = saved.get("best_epoch"), saved["global_update"]
        generator.set_state(saved["loader_generator"].cpu())
        val_generator.set_state(saved["val_loader_generator"].cpu())
        restore_rng(saved["rng"], device)
    if start_epoch >= args.epochs:
        print(f"Checkpoint has already completed {start_epoch} epochs", flush=True)
        return
    run_config = vars(args).copy()
    data_identity = {"train": train_data.identity, "val": val_data.identity}
    if saved:
        provenance = saved.get("pretrained_report")
    elif args.initial_checkpoint:
        provenance = {"backbones": model.pretrained_report,
                      "initial_checkpoint": {"path": args.initial_checkpoint, "sha256": initial_checkpoint_sha256,
                                             "epoch": initial_checkpoint_epoch,
                                             "parent_pretrained_report": parent_pretrained_report}}
    else:
        provenance = pretrained_provenance(model, args.weight_dir)
    run_config.update(initial_model_sha256=initial_model_sha256,
                      initial_model_tensor_hashes=initialization, pretrained_report=provenance,
                      initial_hash_available=initial_model_sha256 is not None,
                      initialization_mode=mode,
                      initial_checkpoint=(saved["run_config"].get("initial_checkpoint") if saved else args.initial_checkpoint),
                      initial_checkpoint_sha256=initial_checkpoint_sha256,
                      initial_checkpoint_epoch=initial_checkpoint_epoch,
                      official_test_used_for_selection=test_selected_recipe,
                      checkpoint_selection_uses_test=False, **reference)
    write_json(output / "run_config.json", {**run_config, "model_config": config.to_dict(),
                                             "pretrained_report": provenance,
                                             "data_identity": data_identity, "partial": partial})
    total_updates = math.ceil(len(train_loader) / args.accumulation) * args.epochs
    print(json.dumps({"device": str(device), "training_images": len(train_data), "validation_images": len(val_data),
                      "partial": partial, "decoder": args.decoder, "backbone": args.backbone,
                      "val_tta": args.val_tta, "val_tta_sizes": args.val_tta_sizes,
                      "hard_pixel_weight": args.hard_pixel_weight,
                      "hard_pixel_quota": args.hard_pixel_quota,
                      "initial_model_sha256": initial_model_sha256, "initialization_mode": mode,
                      "official_test_used_for_selection": test_selected_recipe,
                      "checkpoint_selection_uses_test": False}), flush=True)
    for epoch in range(start_epoch, args.epochs):
        started = time.monotonic()
        frozen = epoch < args.freeze_epochs
        model.freeze_backbones(frozen)
        model.train()
        optimizer.zero_grad(set_to_none=True)
        loss_sums, seen = {}, 0
        hard_diagnostics = HardPixelDiagnostics(train_data, args.hard_pixel_weight, args.hard_pixel_quota)
        for step, batch in enumerate(train_loader):
            # The final, shorter accumulation window must not be divided by the
            # nominal accumulation count. Weight by actual images, including a
            # short final minibatch, to preserve mean gradient scaling.
            window_start = (step // args.accumulation) * args.accumulation
            window_end = min(window_start + args.accumulation, len(train_loader))
            window_samples = min(window_end * args.batch_size, len(train_data)) - window_start * args.batch_size
            factor = max(0.01, (1.0 - update / max(1, total_updates)) ** 0.9)
            optimizer.param_groups[0]["lr"] = 0.0 if frozen else args.backbone_lr * factor
            optimizer.param_groups[1]["lr"] = args.head_lr * factor
            images = batch["image"].to(device, non_blocking=True)
            target = batch["mask"].to(device, non_blocking=True)
            with autocast_context(device, args.amp):
                predictions = model(images)
                losses = criterion(predictions, target)
                loss = losses["loss_total"] * (len(images) / window_samples)
            if not torch.isfinite(loss):
                raise FloatingPointError(f"Non-finite loss at epoch {epoch + 1}, batch {step + 1}")
            scaler.scale(loss).backward()
            hard_diagnostics.update(criterion, batch, step)
            logged_losses = {name: float(value.detach()) for name, value in losses.items()}
            logged_losses.setdefault("loss_hard_pixels", 0.0)
            logged_losses.setdefault("loss_hard_pixels_weighted", 0.0)
            logged_losses["loss_base"] = logged_losses["loss_total"] - logged_losses["loss_hard_pixels_weighted"]
            logged_losses["hard_to_base_ratio"] = (logged_losses["loss_hard_pixels_weighted"] /
                                                    max(logged_losses["loss_base"], 1e-12))
            for name, value in logged_losses.items():
                loss_sums[name] = loss_sums.get(name, 0.0) + value * len(images)
            seen += len(images)
            if step + 1 == window_end:
                scaler.unscale_(optimizer)
                if args.gradient_clip > 0:
                    torch.nn.utils.clip_grad_norm_(model.parameters(), args.gradient_clip, error_if_nonfinite=True)
                scaler.step(optimizer)
                scaler.update()
                optimizer.zero_grad(set_to_none=True)
                update += 1
            if step == 0 or (step + 1) % 25 == 0 or step + 1 == len(train_loader):
                print(f"epoch {epoch + 1}/{args.epochs} batch {step + 1}/{len(train_loader)} "
                      f"loss={logged_losses['loss_total']:.5f} base={logged_losses['loss_base']:.5f} "
                      f"hard_raw={logged_losses['loss_hard_pixels']:.5f} "
                      f"hard_weighted={logged_losses['loss_hard_pixels_weighted']:.5f} "
                      f"hard/base={logged_losses['hard_to_base_ratio']:.5f} frozen={frozen}", flush=True)
                current_diagnostics = hard_diagnostics.result(epoch + 1, training_loss_means(loss_sums, seen))
                current_diagnostics.update(partial_epoch=True, images_seen=seen)
                write_json(output / "hard_pixel_diagnostics_current.json", current_diagnostics)
        mean_losses = training_loss_means(loss_sums, seen)
        diagnostics_path = output / f"hard_pixel_diagnostics_epoch_{epoch + 1:03d}.json"
        final_diagnostics = hard_diagnostics.result(epoch + 1, mean_losses)
        final_diagnostics.update(partial_epoch=False, images_seen=seen)
        write_json(diagnostics_path, final_diagnostics)
        write_json(output / "hard_pixel_diagnostics_current.json", final_diagnostics)
        metrics = evaluate_loader(model, val_loader, device, args.amp,
                                  tta=args.val_tta, tta_sizes=args.val_tta_sizes)
        # Custom validation pools all saved validation images across its scenes.
        score = metrics["miou"] if custom_validation else metrics["scenes"]["Moon_5"]["miou"]
        improved = score > best
        if improved:
            best, best_epoch = score, epoch + 1
        record = {"epoch": epoch + 1, "training_loss": mean_losses,
                  "hard_pixel_diagnostics": str(diagnostics_path.resolve()),
                  "validation": metrics, "best_miou": best, "best_epoch": best_epoch,
                  "selection_scene": selection_scene, "selection_score": score,
                  "official_test_used_for_selection": test_selected_recipe, "checkpoint_selection_uses_test": False,
                  "backbones_frozen": frozen, "seconds": time.monotonic() - started,
                  "partial": partial, "global_update": update}
        write_json(output / f"validation_epoch_{epoch + 1:03d}.json", record)
        with (output / "history.jsonl").open("a") as stream:
            stream.write(json.dumps(record, ensure_ascii=False) + "\n")
        checkpoint = {"format_version": 1, "model_config": config.to_dict(), "model": model.state_dict(),
                      "optimizer": optimizer.state_dict(), "scaler": scaler.state_dict(),
                      "epoch": epoch + 1, "global_update": update, "best_miou": best, "best_epoch": best_epoch,
                      "metrics": metrics, "run_config": run_config, "data_identity": data_identity,
                      "loader_generator": generator.get_state(), "val_loader_generator": val_generator.get_state(),
                      "rng": rng_state(device), "partial": partial, "pretrained_report": provenance}
        checkpoint.update(official_test_used_for_selection=test_selected_recipe, checkpoint_selection_uses_test=False)
        save_checkpoint(output / "last.pt", checkpoint)
        if improved:
            save_checkpoint(output / ("best_smoke.pt" if partial else "best.pt"), checkpoint)
        write_json(output / "summary.json", {"status": "complete" if epoch + 1 == args.epochs else "running",
                                              "completed_epochs": epoch + 1, "best_epoch": best_epoch,
                                              "best_validation_miou": best, "partial": partial,
                                              "selection_scene": selection_scene, "val_tta": args.val_tta,
                                              "val_tta_sizes": args.val_tta_sizes,
                                              "official_test_used_for_selection": test_selected_recipe,
                                              "checkpoint_selection_uses_test": False})
        print(f"epoch {epoch + 1} {selection_scene} mIoU={score:.6%}; best={best:.6%}", flush=True)


if __name__ == "__main__":
    main()
